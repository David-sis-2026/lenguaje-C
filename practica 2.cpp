#include <stdio.h>

int main (){
	//realice un programa que sume dos numeros

	//definir variables
    int n1 ; 
	int n2 ;
	int suma ;
	
	//entrada 
	printf ( " INGRESE EL PRIMER NUMERO ") ;
	scanf ( "%d", &n1) ;
	printf ( " INGRESE SEGUNDO NUMERO ") ;
	scanf ( "%d", &n2) ;
	
	//Proceso 
	suma=n1+n2 ;
	
	//salida
	printf ( " EL RESULTADO DE LA SUMA ES: %d\n", suma )  ;

return 0;
}
	
	
